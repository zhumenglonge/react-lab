/* =========================================================
 * 本主题内复用的工具函数（非组件，放 .js）
 * ---------------------------------------------------------
 * blockSync：同步忙等，模拟"必须在渲染流程里同步完成的重活"，
 * 用来放大 useEffect / useLayoutEffect 的执行时机差异 ——
 * 谁挡在浏览器绘制之前，一眼就能看出来。
 * ========================================================= */

// 阻塞主线程约 ms 毫秒（空转）。仅用于演示，别在真实业务里这么干。
export function blockSync(ms) {
  const end = performance.now() + ms
  while (performance.now() < end) {
    // 故意空转，占住主线程，模拟同步重活
  }
}
